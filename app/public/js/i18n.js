let lang = 'en';
try { lang = localStorage.getItem('zn_lang') || 'en'; } catch { /* storage may be blocked */ }

export const getLang = () => lang;
export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  try { localStorage.setItem('zn_lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

// t('hello', { name }) for UI strings; L(field) for { en, es } content.
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
export const L = field => (field && typeof field === 'object') ? (field[lang] || field.en || field.es || '') : (field ?? '');

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
}
