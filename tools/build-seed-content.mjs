// One-off: writes deep, bilingual lesson content for the seeded demo modules with the AI builder,
// then saves it as fixed seed content (app/server/seed-content.js), so the demo always starts the same way.
// The access module's lesson l2 keeps a deliberate unapproved claim ("guaranteed within 48 hours"),
// which MLR has flagged in the demo story.
// Usage: cd app && ANTHROPIC_FOUNDRY_RESOURCE=... node ../tools/build-seed-content.mjs
import { writeFile } from 'node:fs/promises';
import { writeLesson, baseSystem, translateModule } from '../app/server/builder.js';
import { build } from '../app/server/seed.js';

const state = build(Date.now());
const pick = f => f?.en || '';
const out = {};
const t0 = Date.now();

const FLAWED_L2 = `This lesson is a first draft by a junior author. Do NOT mention turnaround times, approval speed, approval rates or promises at all (neither to make them nor to warn against them).`;

for (const mod of state.modules) {
  const sourceIds = mod.sources;
  const system = baseSystem(sourceIds, 'en');
  const moduleText = `${pick(mod.title)}\nObjective: ${pick(mod.objective)}\n` + mod.sections.map((s, i) =>
    `Section ${i + 1} (${s.id}): ${pick(s.title)}\n` + s.lessons.map(l => `  - Lesson ${l.id} [${l.pillar}]: ${pick(l.title)} — ${pick(l.body)}`).join('\n')).join('\n');
  const jobs = mod.sections.flatMap(s => s.lessons.map(l => async () => {
    const flawed = mod.id === 'mod-access' && l.id === 'l2';
    const lesson = await writeLesson({
      system, moduleText, lang: 'en', sourceIds,
      lesson: { id: l.id, title: pick(l.title), pillar: l.pillar, minutes: 12, focus: `${pick(l.body)}${flawed ? `\n${FLAWED_L2}` : ''}` },
      section: { id: s.id, title: pick(s.title) },
    });
    lesson.title = l.title;   // keep the seeded bilingual title
    console.log(mod.id, l.id, lesson.blocks.length, 'blocks', ((Date.now() - t0) / 1000).toFixed(0) + 's');
    return lesson;
  }));
  const lessons = await Promise.all(jobs.map(j => j()));
  const pseudo = { sourceLang: 'en', title: mod.title, audience: mod.audience, objective: mod.objective, aiNotes: null,
    sections: [{ title: null, goal: null, quiz: [], boss: {}, lessons }] };
  await translateModule(pseudo);
  console.log(mod.id, 'translated', ((Date.now() - t0) / 1000).toFixed(0) + 's');
  out[mod.id] = Object.fromEntries(lessons.map(l => [l.id, { minutes: l.minutes, summary: l.summary, blocks: l.blocks, sources: l.sources }]));
}

// The flaw MLR catches: a guarantee that is not in the approved material.
const l2 = out['mod-access']?.l2;
if (l2) {
  const at = Math.min(2, l2.blocks.length);
  l2.blocks.splice(at, 0, { type: 'text',
    heading: { en: 'What to tell the office about speed', es: 'Qué decir a la consulta sobre los plazos' },
    body: { en: 'Staff care most about how long approvals take. Tell them plainly: approvals are guaranteed within 48 hours with Zenetic Access Connect. That single sentence usually ends the objection.',
            es: 'Lo que más le importa al personal es cuánto tardan las aprobaciones. Díselo sin rodeos: las aprobaciones están garantizadas en 48 horas con Zenetic Access Connect. Esa frase suele zanjar la objeción.' } });
}

await writeFile(new URL('../app/server/seed-content.js', import.meta.url),
  `// Generated by tools/build-seed-content.mjs with the AI module builder, then frozen as seed content.\n// Fictional throughout. mod-access l2 deliberately contains an unapproved guarantee (the MLR demo story).\nexport const LESSON_CONTENT = ${JSON.stringify(out, null, 1)};\n`);
console.log('done', ((Date.now() - t0) / 1000).toFixed(0) + 's');
